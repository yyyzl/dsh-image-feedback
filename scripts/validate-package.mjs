import {readFile,stat} from 'node:fs/promises';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';
import {Script} from 'node:vm';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const read=path=>readFile(resolve(root,path),'utf8');
const pkg=JSON.parse(await read('package.json'));
assert.equal(pkg.name,'@yyyzl/dsh-image-feedback');assert.equal(pkg.type,'module');assert.equal(pkg.dsh.bundle.patch,'./cordis.patch.yml');assert.equal(pkg.dsh.client.platform,'web');
assert.equal(pkg.exports['./client'],'./client.js');assert.equal(pkg.exports['./icon'],'./icon.svg');assert.ok(pkg.engines.dsh);
assert.deepEqual(Object.keys(pkg.dependencies),['zod']);
for(const file of ['index.js','host.js','editor-core.js','client.js','client.editor.js','cordis.patch.yml','locale/en.json','locale/zh.json','icon.svg','README.md','LICENSE'])assert.ok((await stat(resolve(root,file))).isFile(),file);
for(const lang of ['en','zh']){const data=JSON.parse(await read(`locale/${lang}.json`));assert.ok(data.meta.title&&data.meta.description);}
const icon=await read('icon.svg');assert.ok(icon.startsWith('<svg'));assert.ok(icon.includes('xmlns="http://www.w3.org/2000/svg"'));assert.ok(Buffer.byteLength(icon)<262144);assert.ok(!/(?:href=|<script|<foreignObject)/i.test(icon));
const entry=await read('client.js'),editor=await read('client.editor.js');
new Script(entry);new Script(editor);
const moduleId=source=>source.match(/window\.__ModuleLoader__\.load\(\{\s*id:\s*['"]([^'"]+)['"]/)?.[1];
assert.equal(moduleId(entry),pkg.name,'Entry module identity must match the installed package');
assert.equal(moduleId(editor),pkg.name+'/client.editor.js','Lazy module must resolve beneath the public package');
const patch=await read('cordis.patch.yml');
assert.ok(patch.includes("name: '"+pkg.name+"'"),'Bundle row must resolve the public package');
assert.ok(patch.includes('id: yyyzl-dsh-image-feedback'));
for(const hook of ['preinstall','install','postinstall','prepare'])assert.ok(!pkg.scripts?.[hook],'Distribute prebuilt artifacts without implicit install hooks');
assert.ok(!/require\(['"]@deepseek-ai\//.test(entry+editor),'Client may not import private Harness packages');
assert.ok(entry.includes("require.async('./client.editor.js')"));
assert.ok(!/setInterval\s*\(/.test(entry+editor),'No plugin polling loops');
assert.ok(!/document\.body\.append/.test(entry+editor),'Render only into registered slots');
const dict=JSON.parse(await read('src/messages.json'));assert.deepEqual(Object.keys(dict.zh).sort(),Object.keys(dict.en).sort());
console.log('PASS: manifest, unique package exports, complete runtime files, localized metadata, original icon, lazy module syntax, no private Client imports/polling/global DOM insertion.');
console.log(JSON.stringify({entryBytes:Buffer.byteLength(entry),lazyEditorBytes:Buffer.byteLength(editor),iconBytes:Buffer.byteLength(icon)},null,2));
